#!/usr/bin/env python3
"""Join templates/*.yaml into dist/button-card-templates.yaml.

Each file in templates/ holds ONE button-card template at column 0 (so the folder also works with
`button_card_templates: !include_dir_merge_named templates/` in a YAML-mode dashboard).
The output is the whole `button_card_templates:` block to paste into a UI dashboard's raw configuration editor.

Usage:  python3 tools/build_templates.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = ["# Generated by tools/build_templates.py. Do not edit; edit the files in templates/ instead.",
       "button_card_templates:"]
for f in sorted((root / "templates").glob("*.yaml")):
    text = f.read_text(encoding="utf-8")
    out.append("".join(("  " + line if line.strip() else line) for line in text.splitlines(True)).rstrip("\n"))
dest = root / "dist" / "button-card-templates.yaml"
dest.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {dest} from {len(list((root / 'templates').glob('*.yaml')))} templates")
